const FILTER_LABELS = {
	crimeNo: 'Crime number',
	crimeTypeName: 'Exact crime type',
	crimeTypeContains: 'Crime type contains',
	locationContains: 'Location or statement contains',
	pincode: 'Pincode',
	divisionName: 'Division',
	caseStatus: 'Case status',
	victimName: 'Victim name',
	accusedName: 'Accused name',
	minVictimAge: 'Minimum victim age',
	maxVictimAge: 'Maximum victim age',
	registeredFrom: 'Registered from',
	registeredTo: 'Registered to'
};

const displayValue = value => {
	if (typeof value === 'number' || typeof value === 'boolean') return String(value);
	return String(value || '').slice(0, 160);
};

const buildChatExplainability = ({
	records,
	intent,
	audit,
	role,
	agentMode,
	language
}) => {
	const citedFirs = [...new Set(records
		.map(record => record.CrimeNo)
		.filter(value => value !== null && value !== undefined)
		.map(String)
	)];
	const appliedFilters = Object.entries(intent.filters || {})
		.filter(([, value]) => value !== null && value !== undefined && value !== '')
		.map(([name, value]) => ({
			name,
			label: FILTER_LABELS[name] || name,
			value: displayValue(value)
		}));
	const dataReferences = records.slice(0, 20).map(record => ({
		crimeNo: String(record.CrimeNo),
		availableFields: audit.selectedFields.filter(field =>
			record[field] !== null && record[field] !== undefined && record[field] !== ''
		)
	}));
	const limitReached = records.length === audit.limit;
	const resultText = records.length === 0
		? 'No matching FIR rows were returned by the bounded lookup.'
		: `${records.length} matching FIR row${records.length === 1 ? ' was' : 's were'} returned.`;

	return {
		version: 'evidence-v1',
		dataSource: 'CaseRegistration',
		evidenceStatus: records.length === 0 ? 'NO_MATCHING_RECORDS' : limitReached ? 'BOUNDED_RESULTS' : 'MATCHING_RECORDS',
		resultCount: records.length,
		citedFirs,
		selectedFields: audit.selectedFields,
		appliedFilters,
		sort: audit.sort,
		requestedLimit: audit.limit,
		limitReached,
		dataReferences,
		processingTrace: [
			'Converted the natural-language request into an approved structured search intent.',
			`Applied the ${role} role field and filter allowlist.`,
			appliedFilters.length
				? `Applied ${appliedFilters.length} validated filter${appliedFilters.length === 1 ? '' : 's'}.`
				: 'Applied no record filter; results are bounded by the approved limit.',
			`Executed a server-constructed read-only lookup with a maximum of ${audit.limit} rows.`,
			`${resultText} The language model received only those returned fields for answer synthesis.`
		],
		safeguards: [
			'The language model did not generate or execute database code.',
			'Fields outside the authenticated role were excluded before retrieval.',
			'The evidence panel is generated by server code from the executed intent and returned rows.'
		],
		limitations: [
			limitReached
				? `The result reached the ${audit.limit}-row limit; additional matching records may exist.`
				: 'The panel describes only records returned by this bounded lookup.',
			records.length === 0
				? 'No returned record does not prove that an incident never occurred; spelling, classification, date range, or missing data can affect retrieval.'
				: 'A cited FIR supports retrieval provenance but does not independently prove every statement in the generated prose.',
			'The prose answer is AI-generated and must be checked against the cited fields before operational use.'
		],
		context: {
			agentMode,
			language,
			role
		}
	};
};

module.exports = { buildChatExplainability };
